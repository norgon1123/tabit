/**
 * Provenance — what every survey artifact must be able to answer about itself.
 *
 * rule:design.survey-provenance. The fidelity ladder only works if a reader
 * can tell measurement from declaration without trusting the filename:
 *
 *   T1  live seeded app      — painted truth (census areas, real layout boxes)
 *   T2  static mock via file:// — style truth, partial structure
 *   T3  stylesheet/source only  — DECLARED vocabulary, nothing painted
 *
 * A T3 row presenting itself as measurement is the exact failure the ladder
 * exists to prevent, which is why tier is a required field and not a default.
 */

export const TIERS = /** @type {const} */ (["T1", "T2", "T3"]);

/** Human sentence for a tier — used in reports and file headers. */
export function tierMeaning(tier) {
  switch (tier) {
    case "T1":
      return "measured from the running application";
    case "T2":
      return "measured from a static mock (file://)";
    case "T3":
      return "declared in source; never painted";
    default:
      throw new Error(`unknown tier: ${tier}`);
  }
}

/**
 * Build the stamp. `commit` is the audited repo's HEAD — the audit describes
 * a state of the code, and a census without one cannot be re-derived.
 */
export function provenance({ tier, commit, viewport, generator, now, engine }) {
  if (!TIERS.includes(tier)) throw new Error(`unknown tier: ${tier}`);
  if (!commit) throw new Error("provenance needs the audited repo's commit");
  if (!generator) throw new Error("provenance needs a generator id");
  return {
    tier,
    commit,
    viewport: viewport ?? null,
    generator,
    capturedAt: (now ?? new Date()).toISOString(),
    ...(engine ? { engine } : {}),
  };
}

/** YAML comment block — every survey file opens with this. */
export function provenanceHeader(p, extra = []) {
  const lines = [
    "# GENERATED by /waypoint.design-audit — an OBSERVATION, never a design",
    "# decision. Nothing here is ratified or approved; the design chain reads",
    "# these as proposal inputs (rule:design.audit-observes-only).",
    `# tier: ${p.tier} — ${tierMeaning(p.tier)}`,
    `# commit: ${p.commit}`,
    p.viewport ? `# viewport: ${p.viewport.width}x${p.viewport.height}` : null,
    `# generator: ${p.generator}${p.engine ? ` (${p.engine})` : ""}`,
    `# captured: ${p.capturedAt}`,
    ...extra.map((e) => `# ${e}`),
  ];
  return lines.filter(Boolean).join("\n");
}

/** The same stamp as a JSON object, for style-census.json and friends. */
export function provenanceBlock(p) {
  return { provenance: { ...p, tierMeaning: tierMeaning(p.tier) } };
}
